#!/usr/bin/env node
// Golden prompts for the C# port of the accepted date notes (loop O2, decisions.md 2026-11-19).
// For outside set 5 it records exactly what the benchmark's accepted arm (SOLO_DATES=a2, SOLO_DATES_GATE=2) sent
// for every pair with the found date first, and for some pairs outside the gate. No model is called and nothing
// is cached: fetch is replaced and the request is captured.
//   node scripts/export-solo-dates-fixture.mjs  →  ../server/Zarqa.Tests/Fixtures/solo-date-notes-golden.json
import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

Object.assign(process.env, { SOLO_REVIEW: "opus", OPUS_BASE_URL: "http://127.0.0.1:9/v1", SOLO_DATES: "a2", SOLO_DATES_GATE: "2" });
for (const k of ["SOLO_EXTRA", "SOLO_TIMING", "ONE_DAY_LINE", "EARLY_LINE", "POSTED_ON"]) delete process.env[k];
const here = path.dirname(fileURLToPath(import.meta.url));
const { loadDataset } = await import("../src/dataset.js");
const text = await import("../src/text.js");
const { debateReview, SOLO_SYSTEM } = await import("../src/reviewers/debate.js");

const dataDir = path.join(here, "..", "data", "independent5");
const edge = await loadDataset(dataDir);
const aliasIndex = text.buildAliasIndex(edge.locations);
const byId = new Map(edge.reports.map((r) => [r.id, r]));
const sha = (s) => createHash("sha256").update(s).digest("hex");
const days = (l, f) => (/^\d{4}-\d{2}-\d{2}/.test(l.eventDate || "") && /^\d{4}-\d{2}-\d{2}/.test(f.eventDate || "") ? Math.round((Date.parse(l.eventDate.slice(0, 10)) - Date.parse(f.eventDate.slice(0, 10))) / 86_400_000) : null);
let sent;
globalThis.fetch = async (_url, init) => {
  sent = JSON.parse(init.body);
  return new Response(JSON.stringify({ choices: [{ message: { content: JSON.stringify({ same_item_probability: 0.5, stronger_case: "balanced", overall_probabilities: { clearly_different: 0.2, probably_different: 0.2, unclear: 0.2, probably_same: 0.2, almost_certainly_same: 0.2 } }) } }], usage: {} }), { status: 200 });
};
const side = (r, photos) => ({ description: r.description, location: r.location ?? "", eventDate: r.eventDate ?? null, createdAt: r.createdAt ?? null, photos });
const cases = [];
let outside = 0, datedSystem = null;
for (const p of edge.pairs) {
  const lost = byId.get(p.lostId), found = byId.get(p.foundId);
  const gap = days(lost, found);
  const foundFirst = gap !== null && gap >= 1;
  if (!foundFirst && outside >= 40) continue;
  if (!foundFirst) outside++;
  await debateReview(lost, found, null, { offline: false, useCache: false, aliasIndex, dataDir });
  const system = sent.messages[0].content;
  const parts = sent.messages[1].content;
  const images = parts.filter((x) => x.type === "image_url").length;
  const dated = system !== SOLO_SYSTEM;
  if (dated) datedSystem ??= system;
  // Photos are not in the repository; the test stands files in for them. Lost reports in this set have none.
  cases.push({ gapDays: gap, dated, lost: side(lost, 0), found: side(found, images), text: parts.filter((x) => x.type === "text").map((x) => x.text).join("\n") });
}
const out = { note: "Generated by benchmark/scripts/export-solo-dates-fixture.mjs from data/independent5. Do not edit by hand.", baseSystemSha256: sha(SOLO_SYSTEM), datedSystemSha256: sha(datedSystem), datedSystem, cases };
const dir = path.join(here, "..", "..", "server", "Zarqa.Tests", "Fixtures");
mkdirSync(dir, { recursive: true });
writeFileSync(path.join(dir, "solo-date-notes-golden.json"), JSON.stringify(out, null, 1));
const count = (f) => cases.filter(f).length;
console.log(`${cases.length} cases: ${count((c) => c.dated)} with a date note (${count((c) => c.gapDays === 1)} at one day, ${count((c) => c.gapDays === 2)} at two), ${count((c) => !c.dated && c.gapDays >= 3)} found-first at three days or more without one, ${count((c) => !c.dated && !(c.gapDays >= 1))} others`);
