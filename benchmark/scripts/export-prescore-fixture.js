// Exports golden outputs of the matching text helpers and the preliminary score for the C# port.
// Deterministic synthetic vectors stand in for embeddings, so the fixture needs no API.
//   node scripts/export-prescore-fixture.js  →  ../server/Zarqa.Tests/Fixtures/prescore-golden.json
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { preliminaryScore } from "../src/prescore.js";
import { buildAliasIndex, dateRelation, embeddingText, expandedLocationTokens, tokens } from "../src/text.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const data = path.join(here, "..", "data", "campus");
const raw = JSON.parse(readFileSync(path.join(data, "reports.json"), "utf8"));
const reports = (Array.isArray(raw) ? raw : raw.reports).map(({ id, type, title, category, description, location, campusZone, eventDate }) =>
  ({ id, type, title, category, description, location, campusZone, eventDate }));
const pairsRaw = JSON.parse(readFileSync(path.join(data, "pairs.json"), "utf8"));
const pairs = Array.isArray(pairsRaw) ? pairsRaw : pairsRaw.pairs;
const aliasIndex = buildAliasIndex(JSON.parse(readFileSync(path.join(data, "locations.json"), "utf8")));

// mulberry32 seeded by a string hash: same vector every run.
function vectorFor(id, dims = 16) {
  let h = 2166136261;
  for (const c of id) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  let s = h >>> 0;
  const rand = () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  return Array.from({ length: dims }, () => rand() * 2 - 1);
}

const byId = new Map(reports.map((r) => [r.id, r]));
const lost = reports.filter((r) => r.type === "lost");
const found = reports.filter((r) => r.type === "found");

// Every gold pair plus a deterministic spread of other lost × found pairs.
const pairList = pairs.map((p) => [p.lostId, p.foundId]);
for (let i = 0; i < lost.length; i++) for (let j = i % 5; j < found.length; j += 5) pairList.push([lost[i].id, found[j].id]);

const out = {
  note: "Generated by benchmark/scripts/export-prescore-fixture.js. Do not edit by hand.",
  reports: reports.map((r) => ({
    ...r,
    vector: vectorFor(r.id),
    tokens: tokens(`${r.title} ${r.description}`),
    locationTokens: expandedLocationTokens(r, aliasIndex),
    embeddingText: embeddingText(r, aliasIndex),
  })),
  pairs: pairList.map(([l, f]) => {
    const a = byId.get(l), b = byId.get(f);
    const p = preliminaryScore(a, b, vectorFor(a.id), vectorFor(b.id), aliasIndex);
    return { lostId: l, foundId: f, score: p.score, cosine: p.cosine, parts: p.parts, dateRelation: dateRelation(a, b) };
  }),
};

const target = path.join(here, "..", "..", "server", "Zarqa.Tests", "Fixtures");
mkdirSync(target, { recursive: true });
writeFileSync(path.join(target, "prescore-golden.json"), JSON.stringify(out, null, 1));
console.log(`wrote ${out.reports.length} reports and ${out.pairs.length} pairs`);
